-- PostgreSQL / Supabase migration for appointment workflow.
-- This is additive: it does not alter the existing Render connection,
-- Supabase Storage configuration, or current expediente tables.

CREATE TABLE IF NOT EXISTS public.cita (
    idcita bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_cliente varchar(100) NOT NULL,
    apellido_paterno varchar(100) NOT NULL,
    apellido_materno varchar(100) NOT NULL,
    dni_cliente varchar(15) NOT NULL,
    telefono varchar(20),
    correo varchar(100),
    motivo varchar(1000) NOT NULL,
    id_conciliador integer NOT NULL REFERENCES public.trabajador (idtrabajador),
    id_usuario_creador integer NOT NULL REFERENCES public.usuario (idusuario),
    fecha_hora timestamp without time zone NOT NULL,
    estado varchar(20) NOT NULL DEFAULT 'PROGRAMADA'
        CHECK (estado IN ('PROGRAMADA', 'REPROGRAMADA', 'CANCELADA', 'ATENDIDA', 'NO_ASISTIO', 'CONVERTIDA')),
    observaciones varchar(2000),
    id_expediente integer REFERENCES public.expediente (idexpediente),
    creado_en timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    actualizado_en timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_cita_expediente UNIQUE (id_expediente)
);

CREATE INDEX IF NOT EXISTS ix_cita_conciliador_fecha
    ON public.cita (id_conciliador, fecha_hora);
CREATE INDEX IF NOT EXISTS ix_cita_estado_fecha
    ON public.cita (estado, fecha_hora);

ALTER TABLE public.cita ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.cita FROM PUBLIC, anon, authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE public.cita TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.cita_idcita_seq TO service_role;

-- The Render backend uses its server-side PostgreSQL connection. The browser
-- must never read or write this table directly through the Supabase API.
