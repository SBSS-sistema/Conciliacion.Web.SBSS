-- Historial auditable para traslados de un expediente entre sedes.
-- No crea expedientes nuevos ni modifica las relaciones con personas, materias,
-- audiencias o archivos adjuntos: todos siguen ligados al mismo idexpediente.

CREATE TABLE IF NOT EXISTS public.historial_traslado_expediente (
    idtraslado bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    idexpediente integer NOT NULL REFERENCES public.expediente (idexpediente) ON DELETE CASCADE,
    idsede_origen integer REFERENCES public.sede (idsede),
    idsede_destino integer NOT NULL REFERENCES public.sede (idsede),
    idconciliador_anterior integer REFERENCES public.trabajador (idtrabajador),
    idconciliador_nuevo integer NOT NULL REFERENCES public.trabajador (idtrabajador),
    idtrabajador_actor integer NOT NULL REFERENCES public.trabajador (idtrabajador),
    motivo varchar(500) NOT NULL,
    fecha_traslado timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS ix_historial_traslado_expediente_fecha
    ON public.historial_traslado_expediente (idexpediente, fecha_traslado DESC);

ALTER TABLE public.historial_traslado_expediente ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.historial_traslado_expediente FROM PUBLIC, anon, authenticated;
GRANT SELECT, INSERT ON TABLE public.historial_traslado_expediente TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.historial_traslado_expediente_idtraslado_seq TO service_role;
